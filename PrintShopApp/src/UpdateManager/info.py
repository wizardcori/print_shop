"""
소프트웨어 업데이트 및 배포 시스템에서 사용하는 Release(릴리스), ZIP(เอ셋), Tag(태그)의 개념과 역할을 알기 쉽게 정리해 드립니다.

1. Tag (태그)
개념: Git 저장소의 특정 시점(Commit)에 붙이는 '이름표(마커)'입니다.

역할: "이 소스 코드가 바로 v1.9.3 버전이다"라는 기준점을 Git 역사에 영구적으로 기록합니다. (예: v1.2.6, v1.9.3)

프로그램 내 역할: 현재 저장소에 어떤 버전들이 만들어져 있는지 역사적인 기준 목록을 파악할 때 사용됩니다.

2. Release (릴리스)
개념: Tag를 기반으로 GitHub 상에서 공식적으로 사용자들에게 배포하기 위해 만드는 '배포 판(Release Page)'입니다.

역할: 소스 코드뿐만 아니라, "이 버전은 정식 배포 버전이며 주요 변경 사항(Changelog)은 이렇습니다" 하고 사용자들에게 안내하는 공지 페이지이자 배포 단위입니다.

프로그램 내 역할: 관리자가 앱을 통해 새로운 버전을 배포하면 GitHub에 Release가 생성되며, 최신 버전(version.json)을 판별하는 기준이 됩니다.

3. ZIP (에셋 / Asset)
개념: Release에 첨부되는 실제 배포용 압축 파일(.zip)입니다. (예: update_v1.9.3.zip)

역할: 사용자가 프로그램을 업데이트할 때 실제로 다운로드받는 빌드된 프로그램 파일(실행파일 및 리소스 포함)입니다.

프로그램 내 역할:

사용자가 [⬇️ 로컬 다운로드]를 누르면 이 ZIP 파일을 받아와 로컬에 저장합니다.

관리자가 [🚀 원격 업로드]를 누르면 빌드된 ZIP 파일을 GitHub Release에 에셋으로 첨부합니다.

💡 세 요소의 연계 흐름 (요약)
Tag 생성: 소스코드를 빌드하고 v1.9.3이라는 태그를 만듭니다.

ZIP 파일 첨부: 빌드된 결과물을 update_v1.9.3.zip 파일로 압축하여 에셋(ZIP)으로 준비합니다.

Release 배포: 태그와 ZIP 파일을 묶어서 GitHub에 Release로 최종 발행합니다.

싱크 및 다운로드: 관리 프로그램이 이를 감지하여 version.json을 갱신하고, 사용자들은 이 ZIP 파일을 다운로드하여 안전하게 앱을 업데이트합니다.
"""
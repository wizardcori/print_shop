            disp = saved_dict.get('display', '')
            ip = saved_dict.get('ip', '')
            clean_saved = disp.rsplit(' (', 1)[0] if ' (' in disp else disp
            for item in interfaces:
                d_name, d_ip, is_conn, is_wl = item
                clean_item = d_name.rsplit(' (', 1)[0] if ' (' in d_name else d_name
                if (disp and d_name == disp) or (ip and d_ip == ip) or (clean_saved and clean_item == clean_saved):
                    if require_internet and not is_conn:
                        continue
                    return item
            return None


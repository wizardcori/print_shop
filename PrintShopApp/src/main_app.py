def set_runtime_mode(mode):
    """Change mode only for a development build."""
    global IS_DEVELOPMENT_MODE
    if not MODE_CAN_SWITCH:
        return False
    normalized = str(mode).strip().lower()
    if normalized not in {'development', 'production'}:
        return False
    IS_DEVELOPMENT_MODE = normalized == 'development'
    os.environ['MODE'] = normalized
    if 'CONFIG_FILE' in globals():
        mode_config = configparser.ConfigParser()
        if os.path.exists(CONFIG_FILE):
            mode_config.read(CONFIG_FILE, encoding=CONFIG_ENCODING)
        if not mode_config.has_section('Settings'):
            mode_config.add_section('Settings')
        mode_config.set('Settings', 'runtime_mode', normalized)
        with open(CONFIG_FILE, 'w', encoding=CONFIG_ENCODING) as stream:
            mode_config.write(stream)
    return True


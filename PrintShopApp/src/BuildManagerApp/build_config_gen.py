import os

def main():
    mode = os.environ.get('MODE', 'production').strip().lower()
    if mode != 'development':
        mode = 'production'

    printer_watch = os.environ.get('USE_PRINTER_WATCH', 'false').strip().lower() in ('true', '1', 'yes', 'on')
    build_time_test = os.environ.get('USE_BUILD_TIME_TEST', 'false').strip().lower() in ('true', '1', 'yes', 'on')

    content = f"""# Generated by build_config_gen.py - do not edit.
BUILD_MODE = {repr(mode)}
BUILD_USE_PRINTER_WATCH = {printer_watch}
BUILD_USE_BUILD_TIME_TEST = {build_time_test}
"""

    # 루트 디렉토리에 바로 생성

    script_dir = os.path.dirname(os.path.abspath(__file__))   # .../src/build_script
    src_dir = os.path.dirname(script_dir)                     # .../src
    output_path = os.path.join(src_dir, "build_config_generated.py")
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"[SUCCESS] Generated {output_path}")

if __name__ == '__main__':
    main()